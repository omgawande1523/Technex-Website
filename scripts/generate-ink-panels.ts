/**
 * Generates original placeholder "comic panels" as SVG ink art, one per event,
 * into public/comics/<slug>.svg. Replaces the third-party comic covers that used
 * to live there. Event names come from src/constants/event-details.ts.
 *
 *   npx tsx scripts/generate-ink-panels.ts
 *
 * Output is deterministic (seeded by slug) so re-running produces no diff.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { eventDetails } from "../src/constants/event-details";

const OUT_DIR = join(process.cwd(), "public", "comics");
const W = 600;
const H = 800;
const GOLD = "#d9ad62";
const PAPER = "#0b0906";

function seeded(seedText: string) {
  let h = 2166136261;
  for (let i = 0; i < seedText.length; i++) {
    h ^= seedText.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A tapered brush stroke: a closed path built from a wobbling spine. */
function brushStroke(rand: () => number, x0: number, y0: number, x1: number, y1: number, width: number) {
  const steps = 14;
  const nx = -(y1 - y0);
  const ny = x1 - x0;
  const len = Math.hypot(nx, ny) || 1;
  const ux = nx / len;
  const uy = ny / len;
  const left: string[] = [];
  const right: string[] = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const taper = Math.sin(Math.PI * t) ** 0.6;
    const wob = (rand() - 0.5) * width * 0.5;
    const px = x0 + (x1 - x0) * t + ux * wob;
    const py = y0 + (y1 - y0) * t + uy * wob;
    const w = (width * taper) / 2;
    left.push(`${(px + ux * w).toFixed(1)},${(py + uy * w).toFixed(1)}`);
    right.unshift(`${(px - ux * w).toFixed(1)},${(py - uy * w).toFixed(1)}`);
  }
  return `M${left.join(" L")} L${right.join(" L")} Z`;
}

/** Splits a title into at most 3 lines of roughly equal length. */
function wrap(title: string, max = 11) {
  const words = title.toUpperCase().split(/\s+/);
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    if ((cur + " " + w).trim().length > max && cur) {
      lines.push(cur);
      cur = w;
    } else cur = (cur + " " + w).trim();
  }
  if (cur) lines.push(cur);
  return lines.slice(0, 3);
}

function panel(slug: string, name: string, category: string, number: string) {
  const rand = seeded(slug);
  const strokes: string[] = [];
  for (let i = 0; i < 9; i++) {
    const x0 = 40 + rand() * (W - 80);
    const y0 = 120 + rand() * (H - 300);
    const ang = (rand() - 0.5) * Math.PI * 0.9;
    const l = 160 + rand() * 320;
    const x1 = x0 + Math.cos(ang) * l;
    const y1 = y0 + Math.sin(ang) * l;
    const op = (0.18 + rand() * 0.55).toFixed(2);
    strokes.push(
      `<path d="${brushStroke(rand, x0, y0, x1, y1, 14 + rand() * 46)}" fill="${GOLD}" opacity="${op}"/>`,
    );
  }
  const splats: string[] = [];
  for (let i = 0; i < 26; i++) {
    const r = 1.5 + rand() ** 3 * 18;
    splats.push(
      `<circle cx="${(rand() * W).toFixed(1)}" cy="${(rand() * H).toFixed(1)}" r="${r.toFixed(1)}" fill="${GOLD}" opacity="${(0.3 + rand() * 0.6).toFixed(2)}"/>`,
    );
  }
  const cx = W * (0.35 + rand() * 0.3);
  const cy = H * (0.38 + rand() * 0.12);
  const lines = wrap(name);
  const fontSize = lines.length > 2 ? 64 : 78;
  const textY = H - 70 - (lines.length - 1) * fontSize * 0.92;

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${esc(name)} ink panel">
  <!-- Generated by scripts/generate-ink-panels.ts. Original placeholder art; replace with commissioned panels. -->
  <defs>
    <pattern id="ht" width="10" height="10" patternUnits="userSpaceOnUse" patternTransform="rotate(${(15 + rand() * 30).toFixed(0)})">
      <circle cx="5" cy="5" r="1.6" fill="${GOLD}"/>
    </pattern>
    <radialGradient id="fade" cx="${(cx / W).toFixed(2)}" cy="${(cy / H).toFixed(2)}" r="0.65">
      <stop offset="0" stop-color="#fff"/>
      <stop offset="1" stop-color="#000"/>
    </radialGradient>
    <mask id="htm"><rect width="${W}" height="${H}" fill="url(#fade)"/></mask>
    <filter id="bleed" x="-10%" y="-10%" width="120%" height="120%">
      <feTurbulence type="fractalNoise" baseFrequency="0.035" numOctaves="3" seed="${Math.floor(rand() * 999)}"/>
      <feDisplacementMap in="SourceGraphic" scale="9"/>
    </filter>
  </defs>
  <rect width="${W}" height="${H}" fill="${PAPER}"/>
  <rect width="${W}" height="${H}" fill="url(#ht)" opacity="0.28" mask="url(#htm)"/>
  <g filter="url(#bleed)">
    <circle cx="${cx.toFixed(0)}" cy="${cy.toFixed(0)}" r="${(120 + rand() * 80).toFixed(0)}" fill="none" stroke="${GOLD}" stroke-width="10" opacity="0.85"/>
    ${strokes.join("\n    ")}
    ${splats.join("\n    ")}
  </g>
  <rect x="14" y="14" width="${W - 28}" height="${H - 28}" fill="none" stroke="${GOLD}" stroke-width="6" filter="url(#bleed)"/>
  <g font-family="Barge, 'Arial Black', Impact, sans-serif" fill="${GOLD}">
    <rect x="34" y="34" width="${Math.min(W - 68, 36 + category.length * 17)}" height="40" fill="${PAPER}" stroke="${GOLD}" stroke-width="2"/>
    <text x="48" y="62" font-size="20" letter-spacing="3">${esc(category.toUpperCase())}</text>
    <text x="${W - 44}" y="66" font-size="34" text-anchor="end" opacity="0.7">#${esc(number)}</text>
    ${lines
      .map(
        (l, i) =>
          `<text x="40" y="${(textY + i * fontSize * 0.92).toFixed(0)}" font-size="${fontSize}" font-weight="900" stroke="${PAPER}" stroke-width="10" paint-order="stroke">${esc(l)}</text>`,
      )
      .join("\n    ")}
  </g>
</svg>
`;
}

mkdirSync(OUT_DIR, { recursive: true });
for (const ev of eventDetails) {
  writeFileSync(join(OUT_DIR, `${ev.slug}.svg`), panel(ev.slug, ev.name, ev.category, ev.number));
}
console.log(`Wrote ${eventDetails.length} ink panels to public/comics/`);
