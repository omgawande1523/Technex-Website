/**
 * Converts the finale line ("SEE YOU AT <festival name>") into SVG glyph
 * paths in the Barge display face, so the home Finale can draw it with
 * DrawSVG. Re-run whenever festival.name changes:
 *
 *   npx tsx scripts/text-to-path.ts
 *
 * Writes src/components/home/scenes/Finale/finalePaths.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import opentype from "opentype.js";
import { festival } from "../src/data/festival";

const FONT = join(process.cwd(), "src", "app", "fonts", "og", "Barge-Black.otf");
const OUT = join(process.cwd(), "src", "components", "home", "scenes", "Finale", "finalePaths.ts");
const SIZE = 200;
const lines = ["SEE YOU AT", festival.name.toUpperCase()];

const font = opentype.loadSync(FONT);
const out = lines.map((text, li) => {
  const y = SIZE * 0.9 + li * SIZE * 1.02;
  const glyphs: { d: string }[] = [];
  let x = 0;
  for (const g of font.stringToGlyphs(text)) {
    const path = g.getPath(x, y, SIZE);
    const d = path.toPathData(1);
    if (d) glyphs.push({ d });
    x += (g.advanceWidth ?? 0) * (SIZE / font.unitsPerEm);
  }
  return { text, width: Math.ceil(x), glyphs };
});
const width = Math.max(...out.map((l) => l.width));
const height = Math.ceil(SIZE * 0.9 + (lines.length - 1) * SIZE * 1.02 + SIZE * 0.25);

const file = `/* Generated by scripts/text-to-path.ts from festival.name. Do not edit by hand. */
export const FINALE_VIEWBOX = { width: ${width}, height: ${height} };
export const FINALE_LINES: { text: string; width: number; glyphs: { d: string }[] }[] = ${JSON.stringify(out)};
`;
writeFileSync(OUT, file);
console.log(`Wrote ${OUT} (${out.reduce((n, l) => n + l.glyphs.length, 0)} glyphs, ${width}x${height})`);
